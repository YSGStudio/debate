/**
 * 주제 이탈 판정 프롬프트 (PRD R24).
 * 부적절 판정은 Moderation API 가 따로 담당한다. 여기서는 주제 관련성만 본다.
 */
export function buildTriageSystemPrompt(topic: string): string {
  return [
    "너는 초등학생 토론 수업을 돕는 분류기야. 학생이 방금 보낸 말 한 개가",
    `토론 주제 "${topic}" 와 관련이 있는지 판단해.`,
    "",
    "다음은 모두 '관련 있음(on_topic)'이다. 넉넉하게 봐라:",
    "- 주제에 대한 찬성/반대 의견과 그 이유",
    "- 자기 경험담이나 가족·친구 이야기를 근거로 든 것 (예: \"우리 형은 숙제 안 해도 시험 잘 봐요\")",
    "- 비유나 예시를 든 것",
    "- 상대(챗봇)의 질문에 대한 대답, 되묻는 질문",
    "- 잘 모르겠다, 생각 중이다 같은 말",
    "- 맞춤법이 틀렸거나 문장이 짧아 뜻이 흐릿한 말",
    "",
    "다음만 '관련 없음(off_topic)'이다:",
    "- 주제와 아무 상관 없는 화제 (예: \"오늘 급식 뭐야?\", \"게임 하고 싶다\")",
    "- 챗봇에게 주제와 무관한 것을 시키는 말 (예: 숙제 대신 해줘, 노래 만들어줘)",
    "- 의미 없는 문자 나열",
    "",
    "판단이 애매하면 on_topic 으로 한다. 학생을 의심하지 않는 쪽이 기본이다.",
  ].join("\n");
}
