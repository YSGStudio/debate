/**
 * 개인 토론을 만들 때 교사에게 보여줄 찬성·반대 주장 초안.
 *
 * 교사가 확인하고 고친 값만 저장한다. 대화마다 모델이 주제를 해석하게 두면
 * "숙제는 없어져야 한다" 같은 부정형 주제에서 찬반이 뒤집힌다.
 */
export function buildStanceClaimsPrompt(topic: string, description: string | null): string {
  return [
    "초등학생 토론 수업의 주제를 보고, 찬성 쪽과 반대 쪽이 각각 무엇을 주장하는지 한 문장씩 써라.",
    "",
    "# 규칙",
    "- 찬성은 주제 문장에 동의하는 쪽, 반대는 동의하지 않는 쪽이다.",
    '  예) 주제 "숙제는 없어져야 한다" → 찬성: "숙제를 없애야 한다", 반대: "숙제는 계속 있어야 한다"',
    "- 주제가 질문(\"~할까?\")이면 '그렇다' 쪽이 찬성이다.",
    '  예) 주제 "초등학생에게 스마트폰이 필요할까?" → 찬성: "초등학생에게 스마트폰이 필요하다"',
    "- 주제가 명사(\"스마트폰 사용\")뿐이면 그것을 허용·도입하는 쪽을 찬성으로 본다.",
    "- 두 문장은 서로 정반대여야 한다. 둘 다 옳을 수 있는 문장은 쓰지 않는다.",
    '- "~해야 한다", "~하면 안 된다" 처럼 입장이 분명한 평서문으로 쓴다.',
    "- 초등학생이 바로 이해하는 쉬운 말로, 각각 40자 안으로 쓴다.",
    '- "찬성:", "반대:" 같은 머리말이나 따옴표를 붙이지 않는다.',
    "",
    "# 주제",
    topic,
    description ? `보충 설명: ${description}` : "",
  ]
    .join("\n")
    .trim();
}
