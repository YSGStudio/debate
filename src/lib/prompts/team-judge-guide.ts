/**
 * 팀 토론 발언별 채점 기준표 (ver2 PRD V-R30).
 *
 * AI 심판이 전체 토론방 발언 하나를 볼 때 쓰는 기준이다. 문안을 바꾸려면 이 파일만 고친다.
 * **배점을 바꾸면** DB 제약(0006 마이그레이션의 team_speech_scores check)과
 * `src/lib/team/rules.ts` 의 합산이 함께 흔들린다. 셋을 같이 고칠 것.
 */

export const JUDGE_ITEMS = ["logic", "evidence", "response", "phaseFit"] as const;
export type JudgeItem = (typeof JUDGE_ITEMS)[number];

/** 항목별 최고점. 합이 발언 최고점(5)이다. */
export const JUDGE_MAX: Record<JudgeItem, number> = {
  logic: 2,
  evidence: 1,
  response: 1,
  phaseFit: 1,
};

/** 태도 감점 하한. 0 ~ -3 */
export const ATTITUDE_MIN = -3;

export const SPEECH_MAX_TOTAL = Object.values(JUDGE_MAX).reduce((a, b) => a + b, 0);

export const JUDGE_LABEL: Record<JudgeItem | "attitude", string> = {
  logic: "논리성",
  evidence: "근거의 구체성",
  response: "상대 발언 반영",
  phaseFit: "단계 적합성",
  attitude: "태도",
};

/** 항목 정의. 프롬프트에 그대로 들어간다. */
export const JUDGE_RUBRIC = `
# 발언 채점 기준 (발언 하나당 0~5점 + 태도 감점)

## 논리성 (0~2)
- 2: 주장과 이유가 분명하게 이어진다. "왜냐하면" 이 없어도 이유가 주장을 받친다.
- 1: 주장과 이유가 있지만 연결이 약하거나, 이유가 주장과 조금 어긋난다.
- 0: 이유 없이 주장만 하거나, 무슨 말인지 알기 어렵다.

## 근거의 구체성 (0~1) — 주로 주장·반론꺾기 단계에서 본다
- 1: 사례, 경험, 들은 이야기, 숫자처럼 구체적인 것을 들었다. 초등학생의 개인 경험도 훌륭한 근거다.
- 0: 막연한 말뿐이다 ("그냥 좋아요", "다들 그래요").

## 상대 발언 반영 (0~1) — 주로 반론·반론꺾기 단계에서 본다
- 1: 직전 상대 팀 발언의 내용을 정확히 짚고 거기에 답했다.
- 0: 상대 말과 상관없이 자기 말만 했다.
- 상대 팀 발언이 아직 하나도 없는 첫 발언은 짚을 것이 없으므로 1점을 준다 (불리하지 않게).

## 단계 적합성 (0~1)
- 주장: 자기 팀 입장과 이유를 내세운다.
- 반론: 상대 팀 주장의 약점을 짚는다.
- 반론꺾기: 우리 팀이 받은 반론에 다시 답한다.
- 최종토론: 핵심을 정리하고 마지막으로 호소한다.
- 1: 지금 단계에 맞는 발언이다. 0: 단계와 맞지 않는다.

## 태도 (0 ~ -3, 감점)
- 0: 문제없다. 대부분의 발언은 0 이다.
- -1: 상대를 가볍게 비꼬거나, 주제에서 조금 벗어났다.
- -2: 상대 팀 학생을 깎아내리거나, 주제와 관계없는 말이 대부분이다.
- -3: 욕설, 비속어, 인신공격.
- 반박이 날카로운 것은 감점 대상이 아니다. 사람이 아니라 주장을 공격하면 괜찮다.

## 공통
- 맞춤법, 띄어쓰기, 문장 솜씨는 점수에 넣지 않는다.
- 발언이 짧아도 핵심이 있으면 점수를 준다.
- 같은 팀 앞 발언을 되풀이하기만 하면 논리성을 1 이하로 준다.
`.trim();
